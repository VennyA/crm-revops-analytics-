WITH
	TOTAL_CUSTOMERS AS (
		SELECT
			O.REGION,
			COUNT(C.CUSTOMER_ID) AS TOTAL_CUSTOMERS
		FROM
			CUSTOMERS C
			JOIN LEADS L ON C.LEAD_ID = L.LEAD_ID
			JOIN COMPANIES O ON L.COMPANY_ID = O.COMPANY_ID
		WHERE
			O.REGION IS NOT NULL
		GROUP BY
			O.REGION
	),
	CHURNED_CUSTOMERS AS (
		SELECT
			O.REGION,
			COUNT(H.CUSTOMER_ID) AS CHURNED_CUSTOMERS
		FROM
			CHURN H
			JOIN CUSTOMERS C ON H.CUSTOMER_ID = C.CUSTOMER_ID
			JOIN LEADS L ON C.LEAD_ID = L.LEAD_ID
			JOIN COMPANIES O ON L.COMPANY_ID = O.COMPANY_ID
		WHERE
			O.REGION IS NOT NULL
		GROUP BY
			O.REGION
	)
SELECT
	T.REGION,
	T.TOTAL_CUSTOMERS,
	COALESCE(C.CHURNED_CUSTOMERS, 0) AS CHURNED_CUSTOMERS,
	ROUND(
		COALESCE(C.CHURNED_CUSTOMERS, 0)::NUMERIC / NULLIF(T.TOTAL_CUSTOMERS, 0),
		4
	) AS CHURN_RATE
FROM
	TOTAL_CUSTOMERS T
	LEFT JOIN CHURNED_CUSTOMERS C ON T.REGION = C.REGION
ORDER BY
	CHURN_RATE DESC;

