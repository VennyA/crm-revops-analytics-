WITH
	BEST_CUSTOMERS AS (
		SELECT
			*
		FROM
			CUSTOMERS
		WHERE
			ARR_USD >= (
				SELECT
					PERCENTILE_CONT(0.75) WITHIN GROUP (
						ORDER BY
							ARR_USD
					)
				FROM
					CUSTOMERS
			)
	)
SELECT
	UNNEST(STRING_TO_ARRAY(C.TECH_STACK, '; ')) AS TOOL,
	COUNT(*) AS FREQUENCY
FROM
	COMPANIES C
	JOIN LEADS L ON C.COMPANY_ID = L.COMPANY_ID
	JOIN BEST_CUSTOMERS BC ON L.LEAD_ID = BC.LEAD_ID
GROUP BY
	TOOL
ORDER BY
	FREQUENCY DESC;

